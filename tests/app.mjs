import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { frequencyAt } from '../src/dsp.js';
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
await mkdir('artifacts', { recursive: true });
let app; const errors = [], report = {};
try {
  app = await electron.launch({ executablePath: path.resolve('node_modules/electron/dist/electron.exe'), args: ['.', '--test'], env, timeout: 60000 });
  const page = await app.firstWindow();
  page.on('pageerror', err => errors.push(err.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await page.waitForFunction(() => !!window.waveTest, null, { timeout: 30000 });
  const snap = () => page.evaluate(() => window.waveTest.snapshot());
  report.initial = await snap();
  assert.equal(report.initial.mode, 'idle'); assert.equal(report.initial.count, 0);
  await page.locator('#demo').click();
  await page.waitForTimeout(1200);
  report.demo = await snap(); assert.equal(report.demo.mode, 'demo'); assert.ok(report.demo.heights[0] > 1);
  await page.screenshot({ path: 'artifacts/demo.png' });
  await page.locator('#pause').click(); const frozen = (await snap()).heights[0];
  await page.waitForTimeout(300); assert.equal((await snap()).heights[0], frozen);
  await page.locator('#slices').click();
  await page.screenshot({ path: 'artifacts/slices.png' });
  await page.locator('#pause').click(); assert.ok((await snap()).count < 15);
  await page.locator('#longitudinal').click();
  await page.locator('#capture').click();
  await page.waitForFunction(() => !window.waveTest.snapshot().busy, null, { timeout: 30000 });
  report.liveStart = await snap();
  report.captureMessage = await page.locator('#message').textContent();
  assert.equal(report.liveStart.mode, 'live', report.captureMessage);
  await page.waitForFunction(() => window.waveTest.snapshot().metrics.packets >= 24);
  report.live = await snap();
  assert.equal(report.live.audioState, 'running');
  assert.ok(report.live.tracks.some(t => t.kind === 'audio' && t.state === 'live'));
  assert.ok(report.live.tracks.every(t => t.kind !== 'video' || t.state === 'ended'));
  for (const dt of report.live.metrics.intervals.slice(2)) assert.ok(Math.abs(dt - 50) < .05, 'Unexpected audio interval: ' + dt);
  // A silent, isolated oscillator verifies the worklet independently of other PC audio.
  await page.evaluate(async () => {
    window.testToneContext = new AudioContext();
    await window.testToneContext.audioWorklet.addModule('./audio-worklet.js');
    const node = new AudioWorkletNode(window.testToneContext, 'history-processor');
    const gain = window.testToneContext.createGain(); gain.gain.value = 0;
    window.testToneFrames = [];
    node.port.onmessage = ({ data }) => window.testToneFrames.push({ rms: data.rms, peak: data.bands.indexOf(Math.max(...data.bands)), maximum: Math.max(...data.bands) });
    window.testTone = window.testToneContext.createOscillator(); window.testTone.frequency.value = 1000;
    window.testTone.connect(node).connect(gain).connect(window.testToneContext.destination); window.testTone.start();
    await window.testToneContext.resume();
  });
  await page.waitForFunction(() => window.testToneFrames.length >= 15);
  report.tone = await page.evaluate(() => window.testToneFrames.at(-1));
  await page.evaluate(() => window.testTone.stop());
  await page.waitForFunction(() => window.testToneFrames.at(-1)?.rms === 0 && window.testToneFrames.at(-1)?.maximum === 0);
  report.silence = await page.evaluate(() => window.testToneFrames.at(-1));
  await page.evaluate(() => window.testToneContext.close());
  report.toneFrequency = frequencyAt(report.tone.peak);
  assert.ok(report.tone.rms > .5, 'Worklet did not receive oscillator input');
  assert.ok(Math.abs(report.toneFrequency - 1000) < 100, 'Expected a dominant 1 kHz tone');
  await page.screenshot({ path: 'artifacts/live.png' });
  await page.locator('#interval').fill('100'); await page.locator('#interval').dispatchEvent('input');
  await page.waitForTimeout(900); report.changedInterval = await snap();
  for (const dt of report.changedInterval.metrics.intervals.slice(-4)) assert.ok(Math.abs(dt - 100) < .05);
  await page.locator('#capture').click(); report.stopped = await snap();
  assert.equal(report.stopped.audioState, 'closed'); assert.equal(report.stopped.tracks.length, 0);
  await page.locator('#capture').click();
  await page.waitForFunction(() => window.waveTest.snapshot().mode === 'live' && window.waveTest.snapshot().metrics.packets >= 5);
  report.reconnected = await snap();
  await page.locator('#capture').click();
  await page.locator('#clear').click(); assert.equal((await snap()).heights[0], 0);
  await page.locator('#interval').fill('50'); await page.locator('#interval').dispatchEvent('input');
  await page.locator('#demo').click();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 700));
  await page.waitForTimeout(500); await page.screenshot({ path: 'artifacts/compact.png' });
  report.compact = await page.evaluate(() => ({ width: innerWidth, bodyWidth: document.body.scrollWidth, sidebarWidth: document.querySelector('aside').scrollWidth, sidebarClient: document.querySelector('aside').clientWidth }));
  assert.equal(report.compact.width, report.compact.bodyWidth);
  assert.equal(report.compact.sidebarWidth, report.compact.sidebarClient);
  assert.equal((await snap()).glError, 0); assert.deepEqual(errors, []);
  report.result = 'passed';
} catch (error) { report.result = 'failed'; report.error = error.stack; process.exitCode = 1; }
finally {
  report.errors = errors; await writeFile('artifacts/test-report.json', JSON.stringify(report, null, 2));
  await app?.close(); console.log(JSON.stringify({ result: report.result, error: report.error, toneFrequency: report.toneFrequency, errors }, null, 2));
}
